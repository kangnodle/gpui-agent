#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn code_round_trips_and_unknown_codes_fall_back_to_korean() {
        for language in [Language::English, Language::Korean] {
            assert_eq!(Language::from_code(language.code()), language);
        }
        assert_eq!(Language::from_code("unknown"), Language::Korean);
    }

    #[test]
    fn translates_local_feedback_and_preserves_external_content() {
        assert_eq!(Language::English.text("작업을 중지했습니다."), "Operation cancelled.");
        assert_eq!(
            Language::English.text("로컬 API 서버에 연결할 수 없습니다"),
            "Cannot connect to the local API server"
        );
        assert_eq!(Language::Korean.text("작업을 중지했습니다."), "작업을 중지했습니다.");
        assert_eq!(Language::English.text("External error: 원문 🦀"), "External error: 원문 🦀");
    }
}
